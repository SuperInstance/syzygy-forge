#!/usr/bin/env python3
"""Generate the SYZT-style C header for the primary (euclid) tables and a
machine-readable index. Table id = FNV-1a (32-bit) over the centroid rows
serialised as little-endian int32, row-major — the identity rule the
architecture plan sketches for shard 0010.
"""
import json
import struct
from pathlib import Path

FORGE = Path.home() / "workspace/syzygy-forge"


def fnv1a(data: bytes) -> int:
    h = 2166136261
    for b in data:
        h ^= b
        h = (h * 16777619) & 0xFFFFFFFF
    return h


def fmt_rows(rows, per_line=8):
    out = []
    flat = [v for row in rows for v in row]
    for i in range(0, len(flat), per_line):
        out.append("    " + ", ".join(str(v) for v in flat[i:i + per_line]) + ",")
    return "\n".join(out)


index = {"format": "SYZT v0 (forge prototype)", "tables": []}
hdr = []
hdr.append("/* =============================================================================")
hdr.append(" * syz_tok_tables.h — SYZT v0 learned tone codebooks (GENERATED, do not edit)")
hdr.append(" * -----------------------------------------------------------------------------")
hdr.append(" * Generated by syzygy-forge from tables/table_micro.json / table_full.json.")
hdr.append(" * Trained by integer k-means (T1) on the docks corpus — see the forge README.")
hdr.append(" *")
hdr.append(" * Selection (the inference form frozen here):")
hdr.append(" *     sel = argmax_j ( <inference_rows_j, feat> + inference_bias_j )")
hdr.append(" * which is exactly nearest-centroid over `rows`, since")
hdr.append(" * inference_rows_j = 2*rows_j and inference_bias_j = -||rows_j||^2.")
hdr.append(" * First maximum wins, mirroring syz_ste_select's tie rule.")
hdr.append(" *")
hdr.append(" * Table id = FNV-1a/32 over the centroid rows serialised as little-endian")
hdr.append(" * int32, row-major. A (kernel, table, frame) triple names a result.")
hdr.append(" * With no table selected, the kernel's existing outputs are unchanged.")
hdr.append(" * ========================================================================== */")
hdr.append("#ifndef SYZ_TOK_TABLES_H")
hdr.append("#define SYZ_TOK_TABLES_H")
hdr.append("#include <stdint.h>")
hdr.append("#include <stddef.h>")
hdr.append("")
hdr.append("typedef struct {")
hdr.append("    const char *name;")
hdr.append("    uint32_t id;          /* FNV-1a of the centroid rows (see above) */")
hdr.append("    uint32_t n, k;        /* codewords x feature width */")
hdr.append("    const int32_t *rows;            /* n x k centroids */")
hdr.append("    const int32_t *inference_rows;  /* n x k, = 2 * rows */")
hdr.append("    const int32_t *inference_bias;  /* n, = -||rows_j||^2 */")
hdr.append("} SyzTokTable;")
hdr.append("")

descriptors = []
for name in ("micro", "full"):
    t = json.loads((FORGE / f"tables/table_{name}.json").read_text())
    rows = t["rows"]
    raw = b"".join(struct.pack("<i", v) for row in rows for v in row)
    tid = fnv1a(raw)
    uname = name.upper()
    hdr.append(f"/* {name}: N={t['n']} K={t['k']} features {t['feature_indices']} "
               f"id=0x{tid:08x} */")
    hdr.append(f"static const int32_t SYZT_{uname}_ROWS[{t['n'] * t['k']}] = {{")
    hdr.append(fmt_rows(rows))
    hdr.append("};")
    hdr.append(f"static const int32_t SYZT_{uname}_INF[{t['n'] * t['k']}] = {{")
    hdr.append(fmt_rows(t["inference_rows"]))
    hdr.append("};")
    hdr.append(f"static const int32_t SYZT_{uname}_BIAS[{t['n']}] = {{")
    hdr.append("    " + ", ".join(str(v) for v in t["inference_bias"]) + ",")
    hdr.append("};")
    hdr.append("")
    descriptors.append(
        f'    {{ "{name}", 0x{tid:08x}u, {t["n"]}u, {t["k"]}u, '
        f"SYZT_{uname}_ROWS, SYZT_{uname}_INF, SYZT_{uname}_BIAS }},")
    index["tables"].append({
        "name": name, "n": t["n"], "k": t["k"],
        "feature_indices": t["feature_indices"],
        "table_id_fnv1a": f"0x{tid:08x}",
        "rows_bytes_int32": t["n"] * t["k"] * 4,
        "source_json": f"tables/table_{name}.json",
    })

hdr.append("static const SyzTokTable SYZT_TABLES[] = {")
hdr.extend(descriptors)
hdr.append("};")
hdr.append("#define SYZT_TABLE_COUNT (sizeof SYZT_TABLES / sizeof SYZT_TABLES[0])")
hdr.append("")
hdr.append("#endif /* SYZ_TOK_TABLES_H */")
hdr.append("")

(FORGE / "tables/syz_tok_tables.h").write_text("\n".join(hdr))
(FORGE / "tables/tables_index.json").write_text(json.dumps(index, indent=2) + "\n")
for t in index["tables"]:
    print(t["name"], t["table_id_fnv1a"], f"rows={t['rows_bytes_int32']}B")
print("header written:", FORGE / "tables/syz_tok_tables.h")
